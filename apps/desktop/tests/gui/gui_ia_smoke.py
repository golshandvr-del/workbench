"""Gate 3.3.0 — UI information architecture (owner request: "the AI tab is full of buttons").

* Every rail page (and every Git sub-tab) shows at most ``MAX_VISIBLE_PER_VIEW`` real
  buttons, and no single action bar shows more than ``MAX_PRIMARY`` + ``More ▾``.
* Every command that existed before 3.3.0 is still reachable (button or More-menu item).
* No page repeats a button that only opens another rail page.
* With ``AIWB_UI_TREE=path`` the page → section → button → menu tree is written as Markdown
  (used to regenerate ``docs/specs/UI_TREE.md``).
"""
from __future__ import annotations

import os
import tempfile
import tkinter as tk
from pathlib import Path

import AI_Workbench as wb
from aiwb.ui import actions as ui_actions
from gui_smoke_helpers import wait_for_project_ready

# Commands present before the 3.3.0 rearrangement (from the 3.2.0 UI tree) — none may disappear.
REQUIRED = {
    "home": ["+ New project", "Add existing folder…", "Open selected", "Reveal folder", "Remove from list"],
    "prompt": ["Select recommended context", "Why these files?", "Select all", "Clear", "Build prompt", "Copy prompt",
               "Save prompt…", "Add history to prompt", "Manage custom instructions…"],
    "response": ["Paste & detect format", "Load response / ZIP…", "Analyze / preview files…", "Import diagnostics…",
                 "Response Inbox…", "Context request…", "Import context plan / select requested files",
                 "Save response candidate…", "Compare candidates / choose files…", "Import architecture plan…",
                 "Save validated prompt + output to history", "Mark Verified… (manual review)",
                 "Report manual runtime / test error…", "Refresh workflow", "Projects (multi-agent)…"],
    "history": ["Project versions…", "Refresh", "Report error…", "Search", "Clear", "Save metadata / notes",
                "Delete selected entry…", "Copy prompt", "Copy model output", "Edit prompt as new revision…",
                "Create repair prompt from this step"],
    "run": ["Run…", "Browse…", "Run / simulate selected file…", "Run selected / retry…", "Run all pending…",
            "Remove selected", "Repair prompt from latest failure…", "Build continuation handoff…",
            "Copy report", "Save report…", "Refresh report"],
    "git": ["Refresh Git status / project history", "Create work branch", "Commit changes…", "Push to GitHub…",
            "Review & Sync…", "Check Git", "Install Git", "Update Git", "Add PAT…", "Test Connection",
            "Replace Credential…", "Refresh Accounts", "Disconnect", "Refresh Repositories", "Link to Active Project…",
            "Unlink Project", "Open on GitHub", "Clone Selected…", "Initialize & Link Local…", "Initial Push Review…",
            "Binding Settings…", "Refresh Binding Metadata", "Build Center…", "Sync & Build…"],
    "settings": ["Mobile Companion…", "Validation Profiles…", "Restore Manager…", "Export redacted diagnostics…",
                 "Open application data folder"],
    "profile": ["Save profile", "Restore defaults"],
}
# Buttons that would only duplicate a rail page.
RAIL_DUPLICATES = {"Project Workbench…", "Go to Prompt", "Open Settings…"}


def views(app) -> list[tuple[str, tk.Misc]]:
    out = []
    for key, frame in app.shell.pages.items():
        if key == "git":
            for tab in app.git_subtabs.tabs():
                out.append((f"git/{app.git_subtabs.tab(tab, 'text')}", app.git_subtabs, tab))
        else:
            out.append((key, None, frame))
    return out


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="aiwb-ia-smoke-") as temp:
        os.environ["LOCALAPPDATA"] = str(Path(temp) / "appdata")
        project = Path(temp) / "IA Project"
        project.mkdir()
        (project / "main.py").write_text("print(1)\n", encoding="utf-8")
        root = tk.Tk()
        root.geometry("1280x800")
        tree_md: list[str] = ["# AI Workbench — UI tree (generated by gui_ia_smoke.py)", ""]
        try:
            app = wb.WorkbenchApp(root)
            for name in ("showinfo", "showwarning", "showerror"):
                setattr(wb.messagebox, name, lambda *a, **k: None)
            app.set_workspace(project, focus_project=True)
            wait_for_project_ready(app, root, project)
            app.prefs.set_mode("advanced")
            root.update()
            failures: list[str] = []
            for key, frame in app.shell.pages.items():
                app.shell.show(key)
                root.update()
                subviews = [(key, frame)]
                if key == "git":
                    subviews = []
                    for tab in app.git_subtabs.tabs():
                        app.git_subtabs.select(tab)
                        root.update()
                        name = f"git › {app.git_subtabs.tab(tab, 'text')}"
                        subviews.append((name, app.git_subtabs.nametowidget(tab)))
                        vis = ui_actions.visible_buttons(app.git_subtabs.nametowidget(tab))
                        if len(vis) > ui_actions.MAX_VISIBLE_PER_VIEW:
                            failures.append(f"{name}: {len(vis)} visible buttons {vis}")
                    app.git_subtabs.select(app.git_subtabs.tabs()[0])
                else:
                    vis = ui_actions.visible_buttons(frame)
                    if len(vis) > ui_actions.MAX_VISIBLE_PER_VIEW:
                        failures.append(f"{key}: {len(vis)} visible buttons {vis}")
                    dup = RAIL_DUPLICATES & set(vis)
                    if dup and key != "workbench":
                        failures.append(f"{key}: duplicates a rail page {sorted(dup)}")
                reachable = ui_actions.all_commands([frame])
                missing = [c for c in REQUIRED.get(key, []) if c not in reachable]
                if missing:
                    failures.append(f"{key}: commands no longer reachable {missing}")
                label = wb.__dict__.get("PAGES", None)
                from aiwb.ui.shell import PAGES
                tree_md.append(f"## {PAGES[key][2]} {PAGES[key][0]}" + ("  *(Advanced)*" if PAGES[key][3] else ""))
                for name, view in subviews:
                    if name != key:
                        tree_md.append(f"- sub-tab: **{name.split(' › ')[1]}**")
                        tree_md.extend("  " + ln for ln in ui_actions.describe(view))
                    else:
                        tree_md.extend(ui_actions.describe(view))
                tree_md.append("")
            for bar in [w for w in _all(root) if isinstance(w, ui_actions.ActionBar)]:
                if len(bar.buttons) > ui_actions.MAX_PRIMARY:
                    failures.append(f"action bar with {len(bar.buttons)} primary buttons: {list(bar.buttons)}")
            assert not failures, "\n".join(failures)
            out = os.environ.get("AIWB_UI_TREE")
            if out:
                Path(out).write_text("\n".join(tree_md) + "\n", encoding="utf-8")
        finally:
            root.destroy()
    print(f"IA smoke passed: every page <= {ui_actions.MAX_VISIBLE_PER_VIEW} visible buttons, every bar <= "
          f"{ui_actions.MAX_PRIMARY} primary + More, all pre-3.3.0 commands reachable, no rail duplicates")


def _all(w: tk.Misc):
    for ch in w.winfo_children():
        yield ch
        yield from _all(ch)


if __name__ == "__main__":
    main()
