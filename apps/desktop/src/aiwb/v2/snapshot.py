"""Project State Snapshot + PROJECT_STATUS.md (roadmap 1.19.0 / slice 2E, spec 12.1–12.2, B.1).

Built only from the local store at one ``state_revision`` (never from model text).
Content hash ignores the generation timestamp so an unchanged state is a no-op.
Privacy: no prompts, raw responses, source, secrets or absolute paths — only IDs,
statuses, titles, accepted decisions and evidence references.
"""
from __future__ import annotations

import hashlib
import json
from typing import Any

from .models import SCHEMA_VERSION, now_utc
from .next_action import compute_next_actions

ACTIVE = ("ready", "in_progress", "in_review", "validation_pending")


def build_snapshot(state: dict[str, Any], *, source: dict[str, Any] | None = None, goal: str = "",
                   phase: str = "", previous_hash: str = "", last_published_revision: int = 0,
                   include_task_details: bool = True) -> dict[str, Any]:
    tasks = state["tasks"]
    by = lambda *st: sorted(t["task_id"] for t in tasks.values() if t["status"] in st)  # noqa: E731
    verified = sorted((e for e in state["evidence"].values() if e["verified"]), key=lambda e: e["evidence_id"])
    nxt = compute_next_actions(state)
    snap: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "project_id": state["project_id"],
        "state_revision": int(state["state_revision"]),
        "generated_at_utc": now_utc(),
        "previous_snapshot_hash": previous_hash,
        "source": {"repository_id": (source or {}).get("repository_id", 0),
                   "repository": (source or {}).get("repository", ""),
                   "branch": (source or {}).get("branch", ""),
                   "commit_sha": (source or {}).get("commit_sha", ""),
                   "local_changes_pending": bool((source or {}).get("local_changes_pending", False)),
                   "local_changes_count": int((source or {}).get("local_changes_count", 0))},
        "project": {"goal": goal[:1000], "current_phase": phase[:80]},
        "summary": {"total_tasks": len(tasks), "active_tasks": len(by(*ACTIVE)), "blocked_tasks": len(by("blocked")),
                    "needs_decision": len(by("needs_decision")), "awaiting_review": len(by("in_review")),
                    "validation_pending": len(by("validation_pending")), "verified_complete": len(by("done"))},
        "active_task_ids": by(*ACTIVE),
        "blocked_task_ids": by("blocked"),
        "needs_decision_task_ids": by("needs_decision"),
        "done_task_ids": by("done"),
        "open_decision_ids": sorted(d["decision_id"] for d in state["decisions"].values() if d["status"] == "proposed"),
        "accepted_decisions": [{"decision_id": d["decision_id"], "title": d["title"], "decision": d["decision"][:500]}
                               for d in sorted(state["decisions"].values(), key=lambda d: d["decision_id"])
                               if d["status"] == "accepted"],
        "last_verified_evidence_id": verified[-1]["evidence_id"] if verified else "",
        "last_published_state_revision": last_published_revision,
        "next_action": ({k: nxt[0][k] for k in ("type", "reference_id", "reason")} if nxt else
                        {"type": "none", "reference_id": "", "reason": "nothing waiting"}),
    }
    if include_task_details:
        snap["tasks"] = [{"task_id": t["task_id"], "task_revision": t["task_revision"], "title": t["title"],
                          "status": t["status"], "owner_agent_id": t.get("owner_agent_id", ""),
                          "depends_on": t.get("depends_on", []), "priority": t.get("priority", "medium"),
                          "blocked_reason": t.get("blocked_reason", "") if t["status"] == "blocked" else "",
                          "verified_evidence_ids": sorted(e["evidence_id"] for e in state["evidence"].values()
                                                          if e["subject_id"] == t["task_id"] and e["verified"]
                                                          and e.get("task_revision") == t["task_revision"])}
                         for t in sorted(tasks.values(), key=lambda t: t["task_id"])]
    snap["content_hash"] = content_hash(snap)
    return snap


def content_hash(snap: dict[str, Any]) -> str:
    stable = {k: v for k, v in snap.items() if k not in ("generated_at_utc", "content_hash", "previous_snapshot_hash",
                                                       "last_published_state_revision", "state_revision")}
    return hashlib.sha256(json.dumps(stable, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


def render_status_md(snap: dict[str, Any], state: dict[str, Any]) -> str:
    s, src = snap["summary"], snap["source"]
    tasks = state["tasks"]
    title = lambda tid: tasks.get(tid, {}).get("title", "")  # noqa: E731
    lines = [f"# Project status — {snap['project_id']}", "",
             "> Generated by AI Workbench from local state; not written by a model. Valid only for the state "
             "revision and commit below.", "",
             f"- **State revision:** {snap['state_revision']} · generated {snap['generated_at_utc']}",
             f"- **Source:** {src['repository'] or '(no repository bound)'} · branch `{src['branch'] or '-'}` · "
             f"commit `{(src['commit_sha'] or '-')[:12]}`",
             f"- **Local unpublished source changes:** {'yes (' + str(src['local_changes_count']) + ')' if src['local_changes_pending'] else 'no'}"]
    if snap["project"]["goal"]:
        lines += [f"- **Goal:** {snap['project']['goal']}"]
    lines += ["", "## Summary", "",
              f"| Active | Blocked | Needs decision | In review | Validation pending | Done (verified) | Total |",
              "|---|---|---|---|---|---|---|",
              f"| {s['active_tasks']} | {s['blocked_tasks']} | {s['needs_decision']} | {s['awaiting_review']} | "
              f"{s['validation_pending']} | {s['verified_complete']} | {s['total_tasks']} |"]
    for head, ids in (("Active tasks", snap["active_task_ids"]), ("Blocked", snap["blocked_task_ids"]),
                      ("Needs decision", snap["needs_decision_task_ids"]), ("Done with evidence", snap["done_task_ids"])):
        lines += ["", f"## {head}", ""] + ([f"- {i} — {title(i)} ({tasks[i]['status']})"
                                           + (f": {tasks[i].get('blocked_reason')}" if tasks[i].get('blocked_reason') and tasks[i]['status'] == 'blocked' else "")
                                           for i in ids] or ["- none"])
    lines += ["", "## Open decisions", ""] + ([f"- {d} — {state['decisions'][d]['title']}" for d in snap["open_decision_ids"]] or ["- none"])
    lines += ["", "## Accepted decisions", ""] + ([f"- {d['decision_id']} — {d['title']}: {d['decision']}" for d in snap["accepted_decisions"]] or ["- none"])
    ev = [e for e in state["evidence"].values() if e["verified"] and e["type"] in ("test_run", "build_run", "manual_review")]
    lines += ["", "## Latest verified evidence", ""] + ([f"- {e['evidence_id']} {e['type']} {e['result']} for {e['subject_id']}"
                                                         + (f" @ `{e['source']['commit_sha'][:10]}`" if e['source'].get('commit_sha') else "")
                                                         for e in sorted(ev, key=lambda e: e['evidence_id'])[-10:]] or ["- none"])
    na = snap["next_action"]
    lines += ["", "## Next action (computed by Workbench)", "", f"- **{na['type']}** {na['reference_id']}: {na['reason']}",
              "", "---", f"Snapshot hash `{snap['content_hash'][:16]}` · previous `{(snap['previous_snapshot_hash'] or '-')[:16]}`"]
    return "\n".join(lines) + "\n"


def fallback_summary(snap: dict[str, Any], state: dict[str, Any], limit: int = 6000) -> str:
    """Short in-prompt state for models that cannot read GitHub (spec 12.6 / B.2)."""
    md = render_status_md(snap, state)
    return md if len(md) <= limit else md[:limit] + "\n…(truncated)\n"
